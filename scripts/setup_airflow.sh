#!/bin/bash
# setup_airflow.sh: local Airflow (Astro CLI, runs in Docker) for the clickstream pipeline
# Usage (from the repo root): bash scripts/setup_airflow.sh
# Prerequisites: Docker Desktop running with WSL integration; .env filled in (Ch. 4); dbt deps done (Ch. 6)
#
# 1. Checks Docker, installs the Astro CLI if missing
# 2. Creates the Astro project in airflow/ (astro dev init), removes the example DAG
# 3. Adds the Databricks provider + Cosmos (requirements.txt) and a separate dbt virtualenv (Dockerfile)
# 4. Writes airflow/.env (git-ignored): Databricks connection as the service principal + the values dbt needs
# 5. Writes airflow/docker-compose.override.yml (git-ignored): mounts the repo's dbt/ folder into the containers
# Safe to re-run: existing files are only extended, .env and the override are regenerated.
# References:
#   Astro CLI:             https://www.astronomer.io/docs/astro/cli/overview
#   Databricks connection: https://airflow.apache.org/docs/apache-airflow-providers-databricks/stable/connections/databricks.html
#   Cosmos (dbt in Airflow): https://astronomer.github.io/astronomer-cosmos/
set -euo pipefail

if [ ! -f .env ]; then echo "ERROR: .env not found. Run from the repo root."; exit 1; fi
set -a; source .env; set +a
: "${DATABRICKS_WORKSPACE_URL:?missing in .env}" "${DATABRICKS_HTTP_PATH:?missing in .env}"
: "${DATABRICKS_SP_CLIENT_ID:?missing in .env}" "${DATABRICKS_SP_CLIENT_SECRET:?missing in .env}" "${AZURE_TENANT_ID:?missing in .env}"
REPO_ROOT="$(pwd)"

echo "1. Checking Docker and the Astro CLI..."
if ! docker info > /dev/null 2>&1; then
  echo "ERROR: Docker is not running. Start Docker Desktop (Settings > Resources > WSL integration: on) and re-run."
  exit 1
fi
echo "   Docker $(docker info --format '{{.ServerVersion}}')"
if ! command -v astro > /dev/null; then
  echo "   Astro CLI not installed -> installing (may ask for your sudo password)"
  curl -sSL install.astronomer.io | sudo bash -s
fi
echo "   $(astro version)"

echo "2. Astro project in airflow/..."
mkdir -p airflow
if [ -f airflow/Dockerfile ]; then
  echo "   already initialized -> skipped"
else
  (cd airflow && astro dev init)
  rm -f airflow/dags/exampledag.py airflow/tests/dags/test_dag_example.py
  echo "   created (example DAG removed)"
fi

echo "3. Python packages for Airflow and dbt..."
# azure-identity: needed by the Databricks provider to log in with an Entra ID service principal
for pkg in "apache-airflow-providers-databricks" "azure-identity" "astronomer-cosmos"; do
  grep -q "^$pkg" airflow/requirements.txt || echo "$pkg" >> airflow/requirements.txt
done
# dbt in its own virtualenv, so its dependencies cannot clash with Airflow's (Cosmos best practice)
if ! grep -q "dbt_venv" airflow/Dockerfile; then
  cat >> airflow/Dockerfile <<'DOCKER'

# dbt in a separate virtualenv (used by Cosmos through ExecutionConfig.dbt_executable_path)
RUN python -m venv dbt_venv && \
    . dbt_venv/bin/activate && \
    pip install --no-cache-dir "dbt-core>=1.10,<2.0" "dbt-databricks>=1.10,<2.0" && \
    deactivate
DOCKER
fi
echo "   requirements.txt: $(paste -sd ' ' airflow/requirements.txt)"

echo "4. Writing airflow/.env (connection as the service principal, never committed)..."
# Airflow reads connections from AIRFLOW_CONN_<ID> variables; JSON built with Python so the secret is escaped correctly
CONN=$(python3 -c "import json, os; print(json.dumps({
  'conn_type': 'databricks',
  'host': os.environ['DATABRICKS_WORKSPACE_URL'],
  'login': os.environ['DATABRICKS_SP_CLIENT_ID'],
  'password': os.environ['DATABRICKS_SP_CLIENT_SECRET'],
  'extra': {'azure_tenant_id': os.environ['AZURE_TENANT_ID']}}))")
cat > airflow/.env <<ENV
# Generated by scripts/setup_airflow.sh from the repo .env. Never commit.
AIRFLOW_CONN_DATABRICKS_DEFAULT=$CONN
# Values used by dbt/profiles.yml inside the containers
DATABRICKS_WORKSPACE_URL=$DATABRICKS_WORKSPACE_URL
DATABRICKS_HTTP_PATH=$DATABRICKS_HTTP_PATH
DATABRICKS_CATALOG=${DATABRICKS_CATALOG:-clickstream}
DATABRICKS_SP_CLIENT_ID=$DATABRICKS_SP_CLIENT_ID
DATABRICKS_SP_CLIENT_SECRET=$DATABRICKS_SP_CLIENT_SECRET
ENV
chmod 600 airflow/.env

echo "5. Mounting dbt/ into the Airflow containers (docker-compose.override.yml)..."
cat > airflow/docker-compose.override.yml <<YML
# Generated by scripts/setup_airflow.sh (absolute path of this machine, so git-ignored)
# The dbt project stays in the repo's dbt/ folder; Airflow sees it at /usr/local/airflow/dbt
services:
  scheduler:
    volumes: ["$REPO_ROOT/dbt:/usr/local/airflow/dbt"]
  dag-processor:
    volumes: ["$REPO_ROOT/dbt:/usr/local/airflow/dbt"]
  triggerer:
    volumes: ["$REPO_ROOT/dbt:/usr/local/airflow/dbt"]
  api-server:
    volumes: ["$REPO_ROOT/dbt:/usr/local/airflow/dbt"]
YML

echo "6. Git-ignoring the generated files..."
for p in "airflow/.env" "airflow/docker-compose.override.yml" "airflow/airflow_settings.yaml"; do
  grep -qxF "$p" .gitignore || echo "$p" >> .gitignore
done
git check-ignore -q airflow/.env && echo "   airflow/.env is ignored"

echo
echo "Done. Next: copy the DAG to airflow/dags/, then: cd airflow && astro dev start"

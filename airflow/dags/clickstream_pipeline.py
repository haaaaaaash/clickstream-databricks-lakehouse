"""clickstream_pipeline: daily lakehouse run, Bronze ingestion -> dbt Silver + Gold

Tasks:
    1. ingest_bronze  starts the Databricks job "clickstream-ingest-bronze" (Ch. 5, deployed by the bundle)
                      and waits for it; it runs on serverless compute as the service principal
    2. dbt            one Airflow task per dbt seed / model, each followed by its tests (Cosmos),
                      run on the SQL warehouse as the service principal (dbt/profiles.yml)

Connections and settings come from airflow/.env (generated by scripts/setup_airflow.sh):
    AIRFLOW_CONN_DATABRICKS_DEFAULT   Databricks workspace, login with the Entra ID service principal
    DATABRICKS_*                      values read by dbt/profiles.yml
The DAG is created paused: nothing runs (or costs money) until it is switched on or triggered.

References:
- DatabricksRunNowOperator: https://airflow.apache.org/docs/apache-airflow-providers-databricks/stable/operators/run_now.html
- Cosmos DbtTaskGroup:      https://astronomer.github.io/astronomer-cosmos/getting_started/astro.html
- Cosmos test behavior:     https://astronomer.github.io/astronomer-cosmos/configuration/testing-behavior.html
"""

import os
from datetime import datetime, timedelta
from pathlib import Path

from airflow.providers.databricks.operators.databricks import DatabricksRunNowOperator
from airflow.sdk import dag
from cosmos import DbtTaskGroup, ExecutionConfig, ProfileConfig, ProjectConfig, RenderConfig
from cosmos.constants import TestBehavior

AIRFLOW_HOME = Path(os.environ.get("AIRFLOW_HOME", "/usr/local/airflow"))
DBT_PROJECT_DIR = AIRFLOW_HOME / "dbt"  # the repo's dbt/ folder, mounted by docker-compose.override.yml

# Same profile as on the laptop: dbt/profiles.yml reads its values from environment variables
profile_config = ProfileConfig(
    profile_name="clickstream_lakehouse",
    target_name="dev",
    profiles_yml_filepath=DBT_PROJECT_DIR / "profiles.yml",
)

# dbt runs from its own virtualenv (see airflow/Dockerfile), separate from Airflow's packages
execution_config = ExecutionConfig(dbt_executable_path=str(AIRFLOW_HOME / "dbt_venv" / "bin" / "dbt"))


@dag(
    dag_id="clickstream_pipeline",
    description="Bronze ingestion (Databricks job) -> dbt Silver + Gold (SQL warehouse)",
    schedule="0 6 * * *",  # daily at 06:00 UTC
    start_date=datetime(2026, 10, 1),
    catchup=False,  # no back-fill of past days
    max_active_runs=1,
    is_paused_upon_creation=True,  # no surprise costs: switch on or trigger manually
    default_args={"retries": 1, "retry_delay": timedelta(minutes=2)},
    tags=["clickstream", "databricks", "dbt"],
)
def clickstream_pipeline():
    # 1. Bronze: the job is found by its name, so no job ID is hard-coded
    ingest_bronze = DatabricksRunNowOperator(
        task_id="ingest_bronze",
        databricks_conn_id="databricks_default",
        job_name="clickstream-ingest-bronze",
        wait_for_termination=True,
    )

    # 2. Silver + Gold: Cosmos turns every seed / model into a task, each followed by its tests
    dbt = DbtTaskGroup(
        group_id="dbt",
        project_config=ProjectConfig(DBT_PROJECT_DIR),
        profile_config=profile_config,
        execution_config=execution_config,
        render_config=RenderConfig(test_behavior=TestBehavior.AFTER_EACH),
        operator_args={"install_deps": True},  # runs dbt deps (dbt_utils) before each task
    )

    ingest_bronze >> dbt


clickstream_pipeline()
